#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import matter from "gray-matter";
import { parse as parseYaml } from "yaml";
import { readCanonicalChapter, renderCanonicalMarkdown } from "../src/lib/manuscript.js";
import { mergeBookObjectReferences, numberBookObjects } from "../src/lib/numbering.js";

const root = process.cwd();
const format = process.argv[2];
if (!new Set(["pdf", "epub"]).has(format)) throw new Error("Usage: node tools/build-publication.mjs pdf|epub");
if (format === "pdf") {
  // The reader PDF begins with the same vector TikZ front used by the print
  // wrap. Build that canonical cover before Pandoc/LuaLaTeX so book.tex can
  // include its cropped front panel as page one without rasterization.
  execFileSync(process.execPath, [path.join(root, "tools", "build-cover.mjs")], {
    cwd: root,
    stdio: "inherit",
  });
}
const book = parseYaml(fs.readFileSync(path.join(root, "book.yml"), "utf8"));
const publication = JSON.parse(fs.readFileSync(path.join(root, "publication.json"), "utf8"));
const publicationAuthors = (publication.authors || [])
  .map((author) => author.name)
  .filter(Boolean);
// Print captions for the static figures that stand in for the web's interactive
// widgets. Declarative (the web captions say "drag"/"slide", which is wrong on a
// static plate). The figure PDFs are generated by tools/figures/*.py.
const figureCaptions = JSON.parse(
  fs.readFileSync(path.join(root, "publication", "figures", "captions.json"), "utf8"),
);
const figureRegistry = JSON.parse(
  fs.readFileSync(path.join(root, "publication", "figures", "registry.json"), "utf8"),
).figures;
const chapters = book.parts.flatMap((part) => part.chapters);
const chapterMap = new Map(chapters.map((chapter, index) => [chapter.slug, {
  label: chapter.src === "ch-prelim" ? "Preliminaries" : `Chapter ${index}`,
  title: chapter.title,
}]));
const chapterNumber = new Map(chapters.map((chapter, index) => [
  chapter.slug,
  chapter.src === "ch-prelim" ? "P" : String(index),
]));

// Use exactly the same semantic object registry as the web build. This keeps
// Equation/Figure/Table references stable across HTML, PDF, and EPUB even when
// chapters are reordered.
const publicationObjectReferences = mergeBookObjectReferences(chapters.map((chapter, index) => {
  const body = renderCanonicalMarkdown(readCanonicalChapter(chapter.src).markdown);
  return numberBookObjects(body, {
    chapterLabel: chapter.src === "ch-prelim" ? "P" : String(index),
    chapterSlug: chapter.slug,
    chapterTitle: chapter.title,
  }).refs;
}));

function expandPublicationObjectReferences(source, currentSlug) {
  return source.replace(
    /\[\[(eq|fig|tbl|lst):([a-z0-9-]+)(?:\|([^\]]+))?\]\]/g,
    (whole, type, label, custom) => {
      const aliases = type === "fig" ? [label, `fig-${label}`] : [label];
      const record = aliases.map((key) => publicationObjectReferences.get(key)).find(Boolean);
      if (!record) throw new Error(`${currentSlug}: unknown ${type} reference '${label}'`);
      const text = custom || `${record.kind} ${record.number}`;
      if (format === "pdf" && !custom) return `${record.kind} \\ref{${record.id}}`;
      const href = record.chapterSlug === currentSlug
        ? `#${record.id}`
        : `#${record.id}`;
      return `[${text}](${href})`;
    },
  );
}

function nearestMarkdownSection(source, offset, chapterTitle) {
  const headings = [...source.slice(0, offset).matchAll(/^#{2,3}\s+(.+?)(?:\s+\{#[^}]+\})?\s*$/gm)];
  return (headings.at(-1)?.[1] || chapterTitle || "Executable check")
    .replace(/[*_`]/g, "")
    .trim();
}

function publicationListingLanguage(language) {
  const labels = { py: "Python", python: "Python", sh: "Shell", bash: "Shell", json: "JSON", yaml: "YAML", yml: "YAML", text: "Output" };
  return labels[language] || language.replace(/(^|-)([a-z])/g, (_, space, letter) => `${space ? " " : ""}${letter.toUpperCase()}`);
}

function numberPublicationListings(source, chapter) {
  let count = 0;
  return source.replace(
    /^```([a-z0-9-]+)[ \t]*\n([\s\S]*?)^```[ \t]*(?:\n\{#(lst-[a-z0-9-]+)\s+caption="([^"]+)"\})?/gm,
    (whole, language, code, explicitId, explicitCaption, offset) => {
      count += 1;
      const number = `${chapterNumber.get(chapter.slug)}.${count}`;
      const id = explicitId || `lst-${chapter.slug}-${count}`;
      const caption = explicitCaption || `${nearestMarkdownSection(source, offset, chapter.title)}: executable check`;
      const languageLabel = publicationListingLanguage(language);
      const displayedCaption = format === "pdf" ? caption : `Listing ${number}. ${caption}`;
      return (
        `::: {#${id} .code-listing data-number="${number}" data-language="${languageLabel}"}\n` +
        `[${displayedCaption}]{.listing-caption}\n\n` +
        `\`\`\`${language}\n${code}\`\`\`\n` +
        `:::`
      );
    },
  );
}

function numberPublicationEquations(source, chapter) {
  const protectedCode = [];
  source = source.replace(/(^|\n)([ \t]*)(`{3,}|~{3,})[^\n]*\n[\s\S]*?\n\2\3(?=\n|$)/g,
    (value) => {
      const token = `\u0000KBPUBCODE${protectedCode.length}\u0000`;
      protectedCode.push([token, value]);
      return token;
    });
  let count = 0;
  source = source.replace(
    /\$\$([\s\S]*?)\$\$(?:[ \t]*\n[ \t]*\{#(eq-[a-z0-9-]+)\})?/g,
    (whole, math, explicitId, offset) => {
      count += 1;
      const number = `${chapterNumber.get(chapter.slug)}.${count}`;
      const id = explicitId || `eq-${chapter.slug}-${count}`;
      const lineStart = source.lastIndexOf("\n", offset) + 1;
      const before = source.slice(lineStart, offset);
      const indent = /^[ \t]*$/.test(before) ? before : "";
      if (format === "pdf") {
        const equationBody = math.trim().split("\n").map((line) => `${indent}${line}`).join("\n");
        // Raw amsmath is used here because Pandoc's TeX-math reader rejects
        // \tag/\label inside $$...$$ and would emit literal dollar signs.
        // The equation counter is already chapter-scoped, including the P
        // namespace of the reference chapter.
        return (
          `\\begin{equation}\n` +
          `${indent}\\label{${id}}\n` +
          `${equationBody}\n` +
          `${indent}\\end{equation}`
        );
      }
      return (
        `::: {#${id} .numbered-equation}\n` +
        `${indent}$$${math}$$\n` +
        `${indent}[(${number})](#${id}){.equation-number}\n` +
        `${indent}:::`
      );
    },
  );
  for (const [token, value] of protectedCode) source = source.split(token).join(value);
  return source;
}

// Exercise and proof list items often carry a column-0 `$$…$$` display-math
// block. Pandoc reads the un-indented block as ending the list, so every
// indented line that follows (the prose, the `Hint`, and its `::: hint-body`
// fenced div) is re-parsed as a top-level verbatim code block — dumping raw
// `$…$` math and literal `:::` fences into the PDF. Indenting such a block to
// the list-content column keeps the whole item together. A block is treated as
// living inside a list only when the next non-blank line is itself indented.
function indentDisplayMathInLists(md) {
  const lines = md.split("\n");
  const out = lines.slice();
  const marker = /^(\s*)(\d+\.|[a-z]\.|[ivx]+\.|[-*+])(\s+)\S/;
  // The list-content column of a line: for a list-item marker it is the column
  // where the item body begins; for an indented continuation it is its own
  // indent; otherwise 0 (not part of a list).
  const contentIndent = (line) => {
    if (line === undefined) return 0;
    const m = line.match(marker);
    if (m) return m[1].length + m[2].length + m[3].length;
    const c = line.match(/^( +)\S/);
    return c ? c[1].length : 0;
  };
  const nonBlank = (from, dir) => {
    let x = from;
    while (x >= 0 && x < lines.length && lines[x].trim() === "") x += dir;
    return x >= 0 && x < lines.length ? lines[x] : undefined;
  };
  let i = 0;
  while (i < lines.length) {
    if (/^\$\$/.test(lines[i])) {
      let j = i;
      const single = /^\$\$.*\$\$\s*$/.test(lines[i]);
      if (!single) { j = i + 1; while (j < lines.length && !/\$\$\s*$/.test(lines[j])) j++; }
      // Indent the block to the deeper of its two list neighbours, so it stays
      // inside its (possibly nested) item instead of terminating the list. Only
      // act when the *preceding* non-blank line is itself list content: a block
      // that merely precedes a list (e.g. inside a worked-example div) must stay
      // at column 0, or a bare 4-space indent would make it a verbatim block.
      const prevIndent = contentIndent(nonBlank(i - 1, -1));
      const indent = Math.max(prevIndent, contentIndent(nonBlank(j + 1, +1)));
      if (prevIndent > 0 && indent >= 2) {
        const pad = " ".repeat(indent);
        for (let m = i; m <= j; m++) out[m] = pad + out[m];
      }
      i = j + 1;
    } else i++;
  }
  return out.join("\n");
}

// Convert \(..\) inline math to $..$, mapping vertical bars to their LaTeX
// commands so they cannot be mistaken for pipe-table delimiters: \|x\| (norm)
// to \lVert x\rVert and |x| (absolute value) to \lvert x\rvert. Shared by the
// table converter (per cell) and the main text pass.
function convertInlineMath(s) {
  return s.replace(/\\\(([\s\S]*?)\\\)/g, (_, math) => {
    const safeMath = math.trim()
      .replace(/\\\|([^|\n]+)\\\|/g, "\\lVert $1\\rVert{}")
      .replace(/\|([^|\n]+)\|/g, "\\lvert $1\\rvert{}");
    return `$${safeMath}$`;
  });
}

// The migrated corpus stores comparison tables as Pandoc *simple tables* marked
// by a `---- ---- ----` rule. Parsing those is disabled in the reader, because
// their cells are separated by whitespace runs yet not padded to the dash
// columns (\(..\) math is narrower than its rendered form), so the fixed-width
// reader slices cells wrong. Instead we rewrite each simple table to a
// delimiter-based *pipe table* here, while the
// dash rule still marks the original column positions; pipe tables are immune
// to the width change, so `+pipe_tables` can then parse them safely.
function convertSimpleTablesToPipe(md, chapter) {
  const lines = md.split("\n");
  const out = [];
  const ruleRe = /^\s*-{3,}(?:\s+-{3,})+\s*$/;   // >=2 dash groups: a table rule
  let i = 0;
  let tableNumber = 0;
  let sectionTitle = chapter.title;
  while (i < lines.length) {
    const heading = lines[i].match(/^#{2,3}\s+(.+?)(?:\s+\{#[^}]+\})?\s*$/);
    if (heading) sectionTitle = heading[1].replace(/[*_`]/g, "").trim();
    if (ruleRe.test(lines[i])) {
      tableNumber += 1;
      const ncol = (lines[i].match(/-{3,}/g) || []).length;
      const indent = lines[i].match(/^\s*/)[0];   // keep the table at its list/div depth
      // The migrated cells are separated by runs of 2+ spaces but are NOT padded
      // to the dash columns (math is written \(..\), narrower than its rendered
      // width), so split on whitespace runs rather than by dash position. Convert
      // each cell's math to $..$ here so no bare | (from |x| or \|x\|) survives to
      // collide with the pipe delimiters; escape any | that still remains.
      const toCells = (s) => {
        const cells = s.trim().split(/\s{2,}/).map((c) =>
          convertInlineMath(c).replace(/(?<!\\)\|/g, "\\|"));
        while (cells.length < ncol) cells.push("");
        if (cells.length > ncol) cells.splice(ncol - 1, cells.length, cells.slice(ncol - 1).join(" "));
        return cells;
      };
      // A header is the non-blank line directly above the rule, itself preceded
      // by a blank line (or the table's start); otherwise the table is headerless.
      const fenceRe = /^\s*:::/;   // a fenced-div boundary is never a table cell
      // The line directly above the rule is the header row (headerless tables
      // put a blank line there instead). Popping it also pulls a header that
      // sits on a list-item continuation line back out of the preceding item.
      let header = new Array(ncol).fill("");
      const prev = out[out.length - 1];
      if (prev !== undefined && prev.trim() !== "" && !ruleRe.test(prev) && !fenceRe.test(prev)) {
        header = toCells(out.pop());
      }
      let j = i + 1;
      const rows = [];
      while (j < lines.length && lines[j].trim() !== "" && !ruleRe.test(lines[j]) && !fenceRe.test(lines[j]))
        rows.push(toCells(lines[j++]));
      if (j < lines.length && ruleRe.test(lines[j])) j++;   // consume a closing rule if present
      // A semantic table label may follow after the blank line Pandoc requires.
      let marker = j;
      while (marker < lines.length && lines[marker].trim() === "") marker++;
      const explicit = lines[marker]?.trim().match(/^\{#(tbl-[a-z0-9-]+)\}$/)?.[1];
      if (explicit) {
        j = marker + 1;
        while (j < lines.length && lines[j].trim() === "") j++;
      }
      const id = explicit || `tbl-${chapter.slug}-${tableNumber}`;
      const number = `${chapterNumber.get(chapter.slug)}.${tableNumber}`;
      const caption = `${format === "epub" ? `Table ${number}. ` : ""}${sectionTitle} {#${id}}`;
      const pipe = (cells) => indent + "| " + cells.join(" | ") + " |";
      // Size columns by their widest cell so wide math (e.g. a quotient kernel)
      // gets enough room instead of overflowing a narrow equal-width column into
      // its neighbour. Pandoc reads these relative dash lengths as column widths
      // when the table has to wrap.
      const widths = Array.from({ length: ncol }, (_, k) => {
        const lens = [header[k]?.length || 0, ...rows.map((r) => r[k]?.length || 0)];
        return Math.max(3, Math.min(48, Math.max(...lens)));
      });
      const sep = indent + "| " + widths.map((w) => "-".repeat(w)).join(" | ") + " |";
      if (out.length && out[out.length - 1].trim() !== "") out.push("");
      out.push(pipe(header), sep, ...rows.map(pipe), `: ${caption}`, "");
      i = j;
      continue;
    }
    out.push(lines[i++]);
  }
  return out.join("\n");
}

function publicationMarkdown(chapter) {
  let source = matter(fs.readFileSync(path.join(root, "manuscript", "chapters", `${chapter.src}.md`), "utf8")).content;
  source = convertSimpleTablesToPipe(source, chapter);
  source = indentDisplayMathInLists(source);
  // The manuscript writes straight quotes as `\"`. The markdown escape
  // suppresses smart typography, so the print edition shows typewriter quotes.
  // Unescape them; pandoc's `smart` extension then curls them properly.
  source = source.replace(/\\"/g, '"');
  // Exercises carry a bare "Hint" line before their `::: hint-body` div (the
  // web renders it as the collapsible's summary). The PDF styles the hint box
  // with its own "Hint." lead, so drop the now-redundant standalone word.
  // Remove only the word; keep the blank line that the fenced div needs before it.
  source = source.replace(
    /^[ \t]*Hint[ \t]*\n(?=[ \t]*\n[ \t]*:{3,}[ \t]*(?:\{\.hint-body\}|hint-body)\b)/gm,
    "",
  );
  // The chapter lead: a styled opener environment in the PDF (filter.lua maps
  // the `.lead` div to kblead); plain italics in the HTML-based EPUB.
  source = source.replace(/<p class="lead">([\s\S]*?)<\/p>/g, (_, text) => {
    const body = text.replace(/<[^>]+>/g, "").trim();
    return format === "pdf" ? `::: {.lead}\n${body}\n:::` : `*${body}*`;
  });
  // Replace each interactive widget with the static JAX-rendered plate that
  // reproduces its default state (publication/figures/<widget>.pdf), captioned
  // from captions.json. Pandoc's implicit_figures turns an image-only paragraph
  // into a numbered figure; the caption's \(...\) math is normalised below.
  source = source.replace(/<figure class="viz" data-widget="([^"]+)"[^>]*>([\s\S]*?)<\/figure>/g,
    (_, widget, inner) => {
      const record = figureRegistry[widget];
      if (!record || record.mode !== "interactive") throw new Error(`Widget ${widget} is absent from the figure registry`);
      // Prefer the declarative print caption; fall back to the widget's own
      // inline <figcaption> (used by widgets that predate captions.json).
      let caption = figureCaptions[widget];
      if (!caption) {
        const cap = inner.match(/<figcaption[^>]*>([\s\S]*?)<\/figcaption>/i);
        caption = cap ? cap[1] : "";
      }
      caption = caption.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
      const figureRecord = publicationObjectReferences.get(widget);
      if (!figureRecord) throw new Error(`${chapter.src}: no number registered for figure ${widget}`);
      const publicationCaption = format === "epub"
        ? `Figure ${figureRecord.number}. ${caption}`
        : caption;
      // PDF and web/EPUB plates are generated from the same Python figure.
      const pdfPlate = path.join(root, record.print);
      const webPlate = path.join(root, record.web);
      if (format === "pdf" && fs.existsSync(pdfPlate))
        return `\n\n![${publicationCaption}](${record.print}){#${figureRecord.id}}\n\n`;
      if (format === "epub" && fs.existsSync(webPlate))
        return `\n\n![${publicationCaption}](${record.web}){#${figureRecord.id}}\n\n`;
      return `> **Interactive figure (${widget}).** ${caption} The interactive version is available in the web edition.`;
    });
  // Static-first figures use the same id for the SVG web/EPUB asset and PDF
  // publication plate. Their interpretive caption stays in the manuscript.
  source = source.replace(
    /<figure class="viz" data-figure="([a-z0-9-]+)"[^>]*>([\s\S]*?)<\/figure>/g,
    (_, figure, inner) => {
      const record = figureRegistry[figure];
      if (!record || record.mode !== "static") throw new Error(`Static figure ${figure} is absent from the figure registry`);
      const cap = inner.match(/<figcaption[^>]*>([\s\S]*?)<\/figcaption>/i);
      const caption = (cap ? cap[1] : "")
        .replace(/<[^>]+>/g, "")
        .replace(/\s+/g, " ")
        .trim();
      if (!caption) throw new Error(`${chapter.src}: static figure ${figure} needs a figcaption`);
      const figureRecord = publicationObjectReferences.get(figure);
      if (!figureRecord) throw new Error(`${chapter.src}: no number registered for figure ${figure}`);
      const publicationCaption = format === "epub"
        ? `Figure ${figureRecord.number}. ${caption}`
        : caption;
      const pdfPlate = path.join(root, record.print);
      const webPlate = path.join(root, record.web);
      if (format === "pdf" && fs.existsSync(pdfPlate))
        return `\n\n![${publicationCaption}](${record.print}){#${figureRecord.id}}\n\n`;
      if (format === "epub" && fs.existsSync(webPlate))
        return `\n\n![${publicationCaption}](${record.web}){#${figureRecord.id}}\n\n`;
      throw new Error(`${chapter.src}: static figure ${figure} is missing its ${format} plate`);
    },
  );
  source = source.replace(/\[\[ch:([a-z0-9-]+)(?:\|([^\]]+))?\]\]/g, (_, slug, custom) => {
    const target = chapterMap.get(slug);
    return custom || (target ? `${target.label}, ${target.title}` : slug);
  });
  source = numberPublicationListings(source, chapter);
  source = numberPublicationEquations(source, chapter);
  source = expandPublicationObjectReferences(source, chapter.slug);
  // A few proof exercises use raw LaTeX \ref commands inside inline math.
  // Prefix those labels just like Markdown fragment links and heading ids.
  source = source.replace(/\\ref\{([a-z][a-z0-9-]*)\}/g,
    (_, id) => /^(?:eq|fig|tbl|lst)-/.test(id) ? `\\ref{${id}}` : `\\ref{${chapter.slug}-${id}}`);
  source = convertInlineMath(source);
  source = source.replace(/\\lt(?![A-Za-z])/g, "<").replace(/\\gt(?![A-Za-z])/g, ">");
  // Chapter-local web anchors are intentionally preserved there. Prefix them
  // only in the single-file formats, where repeated ids such as `summary` and
  // `exercises` would otherwise collide.
  source = source.replace(/\]\(#([a-z][a-z0-9-]*)\)/g,
    (_, id) => /^(?:eq|fig|tbl|lst)-/.test(id) ? `](#${id})` : `](#${chapter.slug}-${id})`);
  source = source.replace(/\{([^}\n]*?)#([a-z][a-z0-9-]*)([^}\n]*)\}/g,
    (_, before, id, after) => /^(?:eq|fig|tbl|lst)-/.test(id)
      ? `{${before}#${id}${after}}`
      : `{${before}#${chapter.slug}-${id}${after}}`);
  // Raw HTML anchor spans are also chapter-local. Pandoc preserves their ids,
  // so keep them in lockstep with the Markdown fragment links above.
  source = source.replace(/\bid="([a-z][a-z0-9-]*)"/g,
    (_, id) => /^(?:eq|fig|tbl|lst)-/.test(id)
      ? `id="${id}"`
      : `id="${chapter.slug}-${id}"`);
  source = source.replace(/\(([^)]+)\.html(?:#[^)]+)?\)/g, "($1.html)");
  return source.trim();
}

function frontmatterMarkdown(item) {
  return fs.readFileSync(
    path.join(root, "manuscript", "frontmatter", `${item.src}.md`),
    "utf8",
  )
    // Social handles like `@azettaai` read as citation keys under citeproc and
    // render as "(azettaai?)". Escape the marker; frontmatter has no citations.
    .replace(/(^|[\s(])@(?=[A-Za-z])/g, "$1\\@")
    .trim();
}

// LaTeX-escape a plain YAML string (part titles and intros from book.yml).
function texEscape(s) {
  return s
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([&%$#_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}");
}

// A part opener page: numeral, title, and the part's intro from book.yml.
function partOpener(part) {
  const [numeral, ...rest] = part.part.split("·").map((s) => s.trim());
  const title = rest.join(" · ") || numeral;
  if (part.chapters[0]?.src === "ch-prelim")
    return `\\kbpartreference{${texEscape(title)}}{${texEscape(part.intro || "")}}{reference}`;
  const artId = `part-${numeral.toLowerCase()}`;
  return `\\kbpart{${texEscape(numeral)}}{${texEscape(title)}}{${texEscape(part.intro || "")}}{${artId}}`;
}

const header = `---
title: "${book.title.replace(/"/g, '\\"')}"
subtitle: "${book.subtitle.replace(/"/g, '\\"')}"
date: "${publication.date}"
lang: ${book.language || "en"}
rights: "Content ${publication.content_license}; original code ${publication.code_license}"
---`;
const publicationMacros = [
  ["kbtagline", book.tagline || book.subtitle],
  ["kbpositioning", book.positioning || ""],
  ["kbshorttitle", book.short_title || book.title],
  ["kbpublicationurl", book.publication_url || "https://www.tahabouhsine.com"],
  ["kbcontentlicense", publication.content_license],
  ["kbcodelicense", publication.code_license],
].map(([name, value]) => `\\renewcommand{\\${name}}{${texEscape(String(value || ""))}}`).join("\n");
const openingMatter = (book.frontmatter || []).map(frontmatterMarkdown);
// The bibliography as a real backmatter chapter: citeproc fills the `#refs`
// div, and the unnumbered heading gives it running heads and a TOC entry.
const bibliographySection = format === "pdf"
  // \chapter* leaves the previous chapter's running-head marks in place;
  // reset them so the bibliography pages carry their own header.
  ? "# Bibliography {.unnumbered}\n\n\\markboth{Bibliography}{Bibliography}\n\n::: {#refs}\n:::"
  : "# Bibliography {.unnumbered}\n\n::: {#refs}\n:::";
// The preliminary reference chapter has its own P namespace. It is neither
// Chapter 0 nor Chapter 1: sections and statements read P.1, P.2, ... while
// the numbered narrative begins cleanly with Chapter 1.
const pdfMainmatter = book.parts.flatMap((part) => {
  const isReference = part.chapters[0]?.src === "ch-prelim";
  return [
    partOpener(part),
    ...(isReference ? ["\\kbpreliminariesmode"] : []),
    ...part.chapters.flatMap((chapter) => [
      `\\kbchapterartset{${texEscape(chapter.src)}}`,
      publicationMarkdown(chapter),
    ]),
    ...(isReference ? ["\\kbmainmattermode"] : []),
  ];
});
const publicationSections = format === "pdf"
  ? [
      // Keep the metadata block and \frontmatter in one segment. The generic
      // segment join inserts \cleardoublepage; separating these two commands
      // created two spurious blank leaves between the colophon and dedication.
      `${header}\n\n${publicationMacros}\n\\frontmatter`,
      ...openingMatter,
      "\\tableofcontents",
      "\\mainmatter\n\\setcounter{chapter}{0}",
      ...pdfMainmatter,
      "\\backmatter",
      bibliographySection,
    ]
  : [header, ...openingMatter, ...chapters.map(publicationMarkdown), bibliographySection];
const combined = publicationSections.join("\n\n\\cleardoublepage\n\n");
const buildDir = path.join(root, ".build", "publication");
const releaseDir = path.join(root, "release");
fs.mkdirSync(buildDir, { recursive: true });
fs.mkdirSync(releaseDir, { recursive: true });
const sourcePath = path.join(buildDir, "book.md");
const outputPath = path.join(releaseDir, `${book.slug || "book"}.${format}`);
fs.writeFileSync(sourcePath, combined);
// PDF compilation is deliberately two-stage. The generated TeX is a stable,
// inspectable compiler artifact: manuscript conversion can be audited without
// conflating it with LuaLaTeX styling or pagination.
const texPath = path.join(buildDir, "book.tex");
const pandocOutputPath = format === "pdf" ? texPath : outputPath;

const common = [
  sourcePath,
  // The migrated corpus contains fixed-width tables emitted by Pandoc's HTML
  // writer. Disable re-parsing those as source tables: altered math delimiters
  // can otherwise shift a cell across the writer's fixed column boundary.
  // Simple/multiline/grid tables stay off (their fixed-width columns mis-parse
  // once math delimiters change width); convertSimpleTablesToPipe rewrites them
  // to pipe tables, which are delimiter-based and safe to parse.
  "--from=markdown+fenced_divs+bracketed_spans+raw_html-simple_tables-multiline_tables-grid_tables+pipe_tables",
  "--bibliography", path.join(root, "bibliography.bib"),
  "--citeproc", "--number-sections", "--top-level-division=chapter",
  "--resource-path", root,
  "--output", pandocOutputPath,
];
common.push(process.env.PDF_DEBUG ? "--verbose" : "--quiet");
if (publicationAuthors.length) {
  common.push("--metadata", "author=" + publicationAuthors.join("; "));
}
if (format === "pdf") {
  // Publication metadata the static preamble cannot know (edition, version):
  // generated per build and included before preamble.tex, whose \providecommand
  // fallbacks then stand down.
  const metaTex = path.join(buildDir, "meta.tex");
  fs.writeFileSync(metaTex, [
    `\\newcommand{\\kbeditionline}{${texEscape(publication.edition || "Draft")} · version ${texEscape(publication.version || "")}}`,
    "",
  ].join("\n"));
  common.push(
    "--to=latex",
    "--standalone",
    // Map semantic fenced divs to the plain statement environments defined by
    // the print style. The generated book.tex remains available for inspection.
    "--lua-filter", path.join(root, "publication", "filter.lua"),
    "--variable", "documentclass=scrbook",
    "--variable", "papersize=letter",
    "--variable", "fontsize=10pt",
    "--variable", "colorlinks=true",
    "--include-in-header", metaTex,
    "--include-in-header", path.join(root, "publication", "preamble.tex"),
  );
}
if (format === "epub") common.push(
  "--toc",
  "--epub-cover-image", path.join(root, "publication", "cover.png"),
  "--css", path.join(root, "publication", "epub.css"),
);
// LuaLaTeX needs a writable font cache. CI and sandboxed agent environments do
// not expose the user-level TeX cache, so keep the cache project-local and
// ignored. This also makes repeated full-book builds substantially faster.
const texCache = path.join(root, ".context", "texlive");
fs.mkdirSync(texCache, { recursive: true });
execFileSync("pandoc", common, {
  cwd: root,
  stdio: "inherit",
  maxBuffer: 64 * 1024 * 1024,
  env: {
    ...process.env,
    TEXMFVAR: texCache,
    TEXMFCACHE: texCache,
  },
});
if (format === "pdf") {
  // Pandoc enables Babel's experimental Lua bidi node filter for LuaLaTeX even
  // for this entirely left-to-right English manuscript. TeX Live 2023, used by
  // current Ubuntu runners, can crash inside `babel-bidi-basic.lua` while
  // shipping a paragraph. Babel is not otherwise needed by this monolingual
  // publication, so remove both branches of Pandoc's generated Babel loader.
  // Keep the surrounding engine conditional intact: empty branches are valid
  // TeX and this is robust to Pandoc changing the order of Babel's options.
  const generatedTex = fs.readFileSync(texPath, "utf8")
    // Pandoc wraps \maketitle in its own frontmatter/mainmatter transition.
    // The TikZ cover already occupies page one and our canonical Markdown
    // starts frontmatter explicitly, so remove that duplicate wrapper. This
    // lets the colophon use the cover verso instead of forcing a blank leaf and
    // an obsolete second title composition.
    .replace(
      /\\begin\{document\}\s*\\frontmatter\s*\\maketitle\s*\\mainmatter/,
      "\\begin{document}\n\\maketitle",
    )
    .replace(
      /^\\usepackage\[[^\]]*\]\{babel\}\s*$/gm,
      "% Babel omitted: monolingual LTR publication",
    )
    // Pandoc versions bundled by older Linux distributions can also emit this
    // language declaration before loading Babel.
    .replace(
      /^\\babelprovide(?:\[[^\]]*\])?\{[^}]*\}\s*$/gm,
      "% Babel language declaration omitted",
    );
  fs.writeFileSync(texPath, generatedTex);
  execFileSync(process.execPath, [path.join(root, "tools", "check-publication-tex.mjs"), texPath], {
    cwd: root,
    stdio: "inherit",
  });
  execFileSync("latexmk", [
    "-lualatex",
    ...(process.env.PDF_DEBUG ? [] : ["-silent"]),
    "-interaction=nonstopmode",
    "-halt-on-error",
    "-file-line-error",
    `-outdir=${buildDir}`,
    texPath,
  ], {
    cwd: root,
    stdio: "inherit",
    maxBuffer: 64 * 1024 * 1024,
    env: {
      ...process.env,
      TEXMFVAR: texCache,
      TEXMFCACHE: texCache,
    },
  });
  execFileSync(process.execPath, [
    path.join(root, "tools", "check-publication-tex.mjs"),
    texPath,
    "--log",
    path.join(buildDir, "book.log"),
  ], { cwd: root, stdio: "inherit" });
  fs.copyFileSync(path.join(buildDir, "book.pdf"), outputPath);
}
console.log(`Built ${path.relative(root, outputPath)}.`);
