#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import matter from "gray-matter";
import { parse as parseYaml } from "yaml";

const root = process.cwd();
const format = process.argv[2];
if (!new Set(["pdf", "epub"]).has(format)) throw new Error("Usage: node tools/build-publication.mjs pdf|epub");
const book = parseYaml(fs.readFileSync(path.join(root, "book.yml"), "utf8"));
const publication = JSON.parse(fs.readFileSync(path.join(root, "publication.json"), "utf8"));
const publicationAuthors = (publication.authors || [])
  .map((author) => author.name)
  .filter(Boolean);
// Print captions for the static figures that stand in for the web's interactive
// widgets. Declarative (the web captions say "drag"/"slide", which is wrong on a
// static plate). The figure PDFs are generated by tools/figures/*.py.
const figureCaptions = JSON.parse(
  fs.readFileSync(path.join(root, "publication", "figures", "captions.json"), "utf8"),
);
const chapters = book.parts.flatMap((part) => part.chapters);
const chapterMap = new Map(chapters.map((chapter, index) => [chapter.slug, {
  label: chapter.src === "ch-prelim" ? "Preliminaries" : `Chapter ${index}`,
  title: chapter.title,
}]));

// Exercise and proof list items often carry a column-0 `$$…$$` display-math
// block. Pandoc reads the un-indented block as ending the list, so every
// indented line that follows (the prose, the `Hint`, and its `::: hint-body`
// fenced div) is re-parsed as a top-level verbatim code block — dumping raw
// `$…$` math and literal `:::` fences into the PDF. Indenting such a block to
// the list-content column keeps the whole item together. A block is treated as
// living inside a list only when the next non-blank line is itself indented.
function indentDisplayMathInLists(md) {
  const lines = md.split("\n");
  const out = lines.slice();
  const marker = /^(\s*)(\d+\.|[a-z]\.|[ivx]+\.|[-*+])(\s+)\S/;
  // The list-content column of a line: for a list-item marker it is the column
  // where the item body begins; for an indented continuation it is its own
  // indent; otherwise 0 (not part of a list).
  const contentIndent = (line) => {
    if (line === undefined) return 0;
    const m = line.match(marker);
    if (m) return m[1].length + m[2].length + m[3].length;
    const c = line.match(/^( +)\S/);
    return c ? c[1].length : 0;
  };
  const nonBlank = (from, dir) => {
    let x = from;
    while (x >= 0 && x < lines.length && lines[x].trim() === "") x += dir;
    return x >= 0 && x < lines.length ? lines[x] : undefined;
  };
  let i = 0;
  while (i < lines.length) {
    if (/^\$\$/.test(lines[i])) {
      let j = i;
      const single = /^\$\$.*\$\$\s*$/.test(lines[i]);
      if (!single) { j = i + 1; while (j < lines.length && !/\$\$\s*$/.test(lines[j])) j++; }
      // Indent the block to the deeper of its two list neighbours, so it stays
      // inside its (possibly nested) item instead of terminating the list. Only
      // act when the *preceding* non-blank line is itself list content: a block
      // that merely precedes a list (e.g. inside a worked-example div) must stay
      // at column 0, or a bare 4-space indent would make it a verbatim block.
      const prevIndent = contentIndent(nonBlank(i - 1, -1));
      const indent = Math.max(prevIndent, contentIndent(nonBlank(j + 1, +1)));
      if (prevIndent > 0 && indent >= 2) {
        const pad = " ".repeat(indent);
        for (let m = i; m <= j; m++) out[m] = pad + out[m];
      }
      i = j + 1;
    } else i++;
  }
  return out.join("\n");
}

function publicationMarkdown(chapter) {
  let source = matter(fs.readFileSync(path.join(root, "manuscript", "chapters", `${chapter.src}.md`), "utf8")).content;
  source = indentDisplayMathInLists(source);
  source = source.replace(/<p class="lead">([\s\S]*?)<\/p>/g, (_, text) => `*${text.replace(/<[^>]+>/g, "")}*`);
  // Replace each interactive widget with the static JAX-rendered plate that
  // reproduces its default state (publication/figures/<widget>.pdf), captioned
  // from captions.json. Pandoc's implicit_figures turns an image-only paragraph
  // into a numbered figure; the caption's \(...\) math is normalised below.
  source = source.replace(/<figure class="viz" data-widget="([^"]+)"[^>]*>[\s\S]*?<\/figure>/g,
    (_, widget) => {
      const caption = (figureCaptions[widget] || "").replace(/\s+/g, " ").trim();
      // EPUB cannot embed a vector PDF; keep the textual pointer there.
      if (format !== "pdf")
        return `> **Interactive figure (${widget}).** ${caption} The interactive version is available in the web edition.`;
      const rel = `publication/figures/${widget}.pdf`;
      return `\n\n![${caption}](${rel})\n\n`;
    });
  source = source.replace(/\[\[ch:([a-z0-9-]+)(?:\|([^\]]+))?\]\]/g, (_, slug, custom) => {
    const target = chapterMap.get(slug);
    return custom || (target ? `${target.label}, ${target.title}` : slug);
  });
  source = source.replace(/\\\(([\s\S]*?)\\\)/g, (_, math) => {
    const safeMath = math.trim()
      .replace(/\\\|([^|\n]+)\\\|/g, "\\lVert $1\\rVert{}")
      .replace(/\|([^|\n]+)\|/g, "\\lvert $1\\rvert{}");
    return `$${safeMath}$`;
  });
  source = source.replace(/\\lt(?![A-Za-z])/g, "<").replace(/\\gt(?![A-Za-z])/g, ">");
  // Chapter-local web anchors are intentionally preserved there. Prefix them
  // only in the single-file formats, where repeated ids such as `summary` and
  // `exercises` would otherwise collide.
  source = source.replace(/\{([^}\n]*?)#([a-z][a-z0-9-]*)([^}\n]*)\}/g,
    (_, before, id, after) => `{${before}#${chapter.slug}-${id}${after}}`);
  source = source.replace(/\(([^)]+)\.html(?:#[^)]+)?\)/g, "($1.html)");
  return source.trim();
}

function frontmatterMarkdown(item) {
  return fs.readFileSync(
    path.join(root, "manuscript", "frontmatter", `${item.src}.md`),
    "utf8",
  ).trim();
}

const header = `---
title: "${book.title.replace(/"/g, '\\"')}"
subtitle: "${book.subtitle.replace(/"/g, '\\"')}"
date: "${publication.date}"
lang: en-US
rights: "Content CC BY-NC-SA 4.0; original code MIT"
---`;
const openingMatter = (book.frontmatter || []).map(frontmatterMarkdown);
const publicationSections = format === "pdf"
  ? [
      header,
      "\\frontmatter",
      ...openingMatter,
      "\\tableofcontents",
      "\\mainmatter",
      ...chapters.map(publicationMarkdown),
    ]
  : [header, ...openingMatter, ...chapters.map(publicationMarkdown)];
const combined = publicationSections.join("\n\n\\cleardoublepage\n\n");
const buildDir = path.join(root, ".build", "publication");
const releaseDir = path.join(root, "release");
fs.mkdirSync(buildDir, { recursive: true });
fs.mkdirSync(releaseDir, { recursive: true });
const sourcePath = path.join(buildDir, "book.md");
const outputPath = path.join(releaseDir, `kernels-the-geometry-of-learning.${format}`);
fs.writeFileSync(sourcePath, combined);

const common = [
  sourcePath,
  // The migrated corpus contains fixed-width tables emitted by Pandoc's HTML
  // writer. Disable re-parsing those as source tables: altered math delimiters
  // can otherwise shift a cell across the writer's fixed column boundary.
  "--from=markdown+fenced_divs+bracketed_spans+raw_html-simple_tables-multiline_tables-grid_tables-pipe_tables",
  "--bibliography", path.join(root, "bibliography.bib"),
  "--citeproc", "--number-sections", "--top-level-division=chapter",
  "--quiet",
  "--resource-path", root,
  "--output", outputPath,
];
if (publicationAuthors.length) {
  common.push("--metadata", "author=" + publicationAuthors.join("; "));
}
if (format === "pdf") common.push(
  "--pdf-engine=lualatex",
  "--variable", "documentclass=scrbook",
  "--variable", "papersize=letter",
  "--variable", "fontsize=10pt",
  "--variable", "mainfont=STIX Two Text",
  "--variable", "mathfont=STIX Two Math",
  "--variable", "colorlinks=true",
  "--include-in-header", path.join(root, "publication", "preamble.tex"),
);
if (format === "epub") common.push(
  "--toc",
  "--epub-cover-image", path.join(root, "publication", "cover.svg"),
);
execFileSync("pandoc", common, { cwd: root, stdio: "inherit", maxBuffer: 64 * 1024 * 1024 });
console.log(`Built ${path.relative(root, outputPath)}.`);
